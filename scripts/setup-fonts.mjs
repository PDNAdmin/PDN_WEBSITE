// Detects Quirkfy in /brand/fonts and writes lib/fonts/display.generated.ts.
// If Quirkfy is missing, headings fall back to Bricolage Grotesque 800 and we log a warning (CLAUDE.md §3.4).
import { copyFileSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { join, dirname, extname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const fontsDir = join(root, "brand", "fonts");
const outDir = join(root, "app", "fonts", "quirkfy");
const genFile = join(root, "lib", "fonts", "display.generated.ts");

const PREF = [".woff2", ".woff", ".otf", ".ttf"];
const files = existsSync(fontsDir)
  ? readdirSync(fontsDir).filter((f) => /^quirkfy/i.test(f) && PREF.includes(extname(f).toLowerCase()))
  : [];

function weightOf(name) {
  const n = name.toLowerCase();
  if (n.includes("black")) return "900";
  if (n.includes("extrabold")) return "800";
  if (n.includes("semibold")) return "600";
  if (n.includes("bold")) return "700";
  if (n.includes("medium")) return "500";
  if (n.includes("light")) return "300";
  return "400";
}

mkdirSync(dirname(genFile), { recursive: true });
rmSync(outDir, { recursive: true, force: true });

if (files.length === 0) {
  console.warn(
    "\x1b[33m[fonts] WARNING: Quirkfy not found in /brand/fonts. Headings fall back to Bricolage Grotesque 800.\x1b[0m",
  );
  writeFileSync(
    genFile,
    `// GENERATED by scripts/setup-fonts.mjs. Do not edit.
// Quirkfy missing: display falls back to Bricolage Grotesque 800.
export const displayFontClass = "";
export const displayWeight = 800;
export const hasQuirkfy = false;
`,
  );
  process.exit(0);
}

// Pick the best format per weight
const byWeight = new Map();
for (const f of files) {
  const w = weightOf(f);
  const cur = byWeight.get(w);
  if (!cur || PREF.indexOf(extname(f).toLowerCase()) < PREF.indexOf(extname(cur).toLowerCase())) {
    byWeight.set(w, f);
  }
}
mkdirSync(outDir, { recursive: true });
const srcs = [];
for (const [w, f] of byWeight) {
  copyFileSync(join(fontsDir, f), join(outDir, f));
  srcs.push(`    { path: "../../app/fonts/quirkfy/${f}", weight: "${w}", style: "normal" }`);
}
const headingWeight = byWeight.has("700") ? 700 : Number([...byWeight.keys()].sort().at(-1));
writeFileSync(
  genFile,
  `// GENERATED by scripts/setup-fonts.mjs. Do not edit.
import localFont from "next/font/local";

const quirkfy = localFont({
  src: [
${srcs.join(",\n")}
  ],
  variable: "--font-quirkfy",
  display: "swap",
  preload: true,
  fallback: ["Bricolage Grotesque", "system-ui", "sans-serif"],
});

export const displayFontClass = quirkfy.variable;
export const displayWeight = ${headingWeight};
export const hasQuirkfy = true;
`,
);
console.log(`[fonts] Quirkfy found: ${[...byWeight.values()].join(", ")}`);
