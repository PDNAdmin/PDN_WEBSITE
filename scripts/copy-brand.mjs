// Copies the official logo files from /brand/logos to /public/brand (never edits the originals).
import { cpSync, existsSync, mkdirSync, readdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "brand", "logos");
const dest = join(root, "public", "brand");

if (!existsSync(src)) {
  console.warn("[copy-brand] brand/logos not found, skipping");
  process.exit(0);
}
mkdirSync(dest, { recursive: true });
cpSync(src, dest, {
  recursive: true,
  filter: (p) => !p.endsWith("README.md"),
});
const count = readdirSync(dest).length;
console.log(`[copy-brand] brand/logos → public/brand (${count} entries)`);

// Emit the River centre-line path as a TS constant so components can draw it without runtime parsing.
import { readFileSync, writeFileSync as _w } from "node:fs";
const svg = readFileSync(join(src, "pdn-mark-centerline.svg"), "utf8");
const d = svg.match(/id="pdn-river"[^>]*\sd="([^"]+)"/)?.[1] ?? svg.match(/\sd="([^"]+)"/)?.[1];
if (d) {
  _w(
    join(root, "lib", "river-path.generated.ts"),
    `// GENERATED by scripts/copy-brand.mjs from brand/logos/pdn-mark-centerline.svg. Do not edit.\nexport const RIVER_VIEWBOX = "0 0 756 780";\nexport const RIVER_STROKE = 57.3;\nexport const RIVER_D =\n  ${JSON.stringify(d)};\n`,
  );
  console.log("[copy-brand] lib/river-path.generated.ts written");
}
